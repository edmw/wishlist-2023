import subprocess

from rich import print

from .printer import Markup


class CheckError(Exception):
    def __init__(self, message: str, rich_message: str):
        super().__init__(message)
        self.rich_message = rich_message


class Checker:
    def __init__(self, simulation: bool = False) -> None:
        self.simulation = simulation

    def _run_and_capture(
        self,
        command: list[str],
        check: bool = True,
    ) -> subprocess.CompletedProcess:
        return subprocess.run(command, check=check, text=True, capture_output=True)  # nosec

    def git_branch_is_tracking(self, branchname: str) -> bool:
        """Returns True, if the local branch has a direct relationship to a
        remote branch, which means it is a tracking branch.
        """
        result = self._run_and_capture(
            [
                "git",
                "config",
                "--get",
                f"branch.{branchname}.merge",
            ],
            check=False,
        )
        is_tracking = result.returncode == 0
        return is_tracking

    def git_branch_is(self, branchname: str) -> None:
        """Checks the current git branch name to match the specified one or exits
        with the error message generated by the given callable.
        """
        result = self._run_and_capture(["git", "branch", "--show-current"])
        if result.stdout.strip() != branchname:
            # git branch’s output does not match
            message = f"Current branch is not {Markup.not_ok(branchname, "'")}"
            if self.simulation:
                print(f"SIMULATION: Would abort because: {message}")
                return
            raise CheckError(Markup.plain(message), message)

    def git_branch_is_uptodate(self) -> None:
        """Checks the current git branch to be up-to-date with its upstream or
        exists with the error message generated by the given callable.
        """
        result = self._run_and_capture(["git", "rev-parse", "HEAD"])
        current_commit_hash = result.stdout
        result = self._run_and_capture(["git", "rev-parse", "@{u}"])
        upstream_commit_hash = result.stdout
        if current_commit_hash != upstream_commit_hash:
            # git branch is out-of-date
            message = f"Current branch is {Markup.not_ok("not up-to-date")} with its upstream"
            if self.simulation:
                print(f"SIMULATION: Would abort because: {message}")
                return
            raise CheckError(Markup.plain(message), message)

    def git_status_is_clean(self) -> None:
        """Checks the actual git branch status to be clean or exits with the error
        message generated by the given callable.
        """
        result = self._run_and_capture(["git", "status", "--porcelain"])
        if result.stdout:
            # git status’ output is not empty => working tree is dirty
            message = f"Working tree is {Markup.not_ok("dirty")}"
            if self.simulation:
                print(f"SIMULATION: Would abort because: {message}")
                return
            raise CheckError(Markup.plain(message), message)
