"""Helper functions for Maker Scripts to check various conditions."""

import subprocess
import sys
from typing import Callable

import make


def _run_and_capture(
    command: list[str],
    check: bool = True,
) -> subprocess.CompletedProcess:
    return subprocess.run(command, check=check, text=True, capture_output=True)  # nosec


def git_branch_is_tracking(branchname: str) -> bool:
    """Returns True, if the local branch has a direct relationship to a
    remote branch, which means it is a tracking branch.
    """
    result = _run_and_capture(
        [
            "git",
            "config",
            "--get",
            f"branch.{branchname}.merge",
        ],
        check=False,
    )
    is_tracking = result.returncode == 0
    return is_tracking


def git_branch_is(branchname: str, or_exit_using: Callable) -> None:
    """Checks the current git branch name to match the specified one or exits
    with the error message generated by the given callable.
    """
    result = _run_and_capture(["git", "branch", "--show-current"])
    if result.stdout.strip() != branchname:
        # git branch’s output does not match
        make.banner(or_exit_using(branchname), fail=True)
        sys.exit(1)


def git_branch_is_uptodate(or_exit_using: Callable) -> None:
    """Checks the current git branch to be up-to-date with its upstream or
    exists with the error message generated by the given callable.
    """
    result = _run_and_capture(["git", "rev-parse", "HEAD"])
    current_commit_hash = result.stdout
    result = _run_and_capture(["git", "rev-parse", "@{u}"])
    upstream_commit_hash = result.stdout
    if current_commit_hash != upstream_commit_hash:
        # git branch is out-of-date
        make.banner(or_exit_using(), fail=True)
        sys.exit(1)


def git_status_is_clean(or_exit_using: Callable) -> None:
    """Checks the actual git branch status to be clean or exits with the error
    message generated by the given callable.
    """
    result = _run_and_capture(["git", "status", "--porcelain"])
    if result.stdout:
        # git status’ output is not empty => working tree is dirty
        make.banner(or_exit_using(), fail=True)
        sys.exit(1)
