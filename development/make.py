# region banner


def banner(
    lines: str | list[str],
    symbol: str = "",
    char: str = "#",
    lf: str = "\n",
    fail: bool = False,
    file: TextIO = sys.stdout,
) -> None:
    """Prints a banner to console.

    If given a string, prints the given string.
    If given a list of strings, prints each given string into a separate line.
    If fail is true, mark the banner with red blinking lights.
    """
    # This is a sanity check while developing which can be safely removed in production.
    assert char, "char must not be empty"  # nosec

    if not isinstance(lines, list):
        lines = [lines]
    char = char[0]
    symbol = symbol[0] if symbol else char

    out = [lf]

    if fail:
        # failure banner
        for line in lines:
            out += [f"🚨 {line}", lf]
        out += [lf]

    else:
        # informational banner
        width = len(max(lines, key=len))

        out += [f"{char * (width + 8)}{lf}"]
        left = symbol * 3
        right = symbol * 3 if symbol == char else ""
        for line in lines:
            out += [f"{left} {line.center(width)} {right}", lf]
        out += [out[1]]

    file.writelines(out)


# endregion

# region subprocess


def subprocess_run(
    command: list[str],
    environment: dict[str, Any] | None = None,
    verbose: bool = False,
    debug: bool = False,
    simulation: bool = False,
) -> None:
    """Runs the given command as subprocess.

    If `verbose` is false (the default), captures all output from the command
    and prints the output only if the command fails.
    If `debug` is true (default is false), prints the command and environment.
    """
    if not environment:
        environment = {}
    if debug or simulation:
        banner("COMMAND", char="-")
        pprint(command)
        banner("ENVIRONMENT", char="-")
        pprint(environment)
    if verbose:
        print()

    if simulation:
        return

    try:
        subprocess.run(  # nosec
            command,
            check=True,
            text=True,
            capture_output=not verbose,
            env={**os.environ.copy(), **environment},
        )
    except subprocess.CalledProcessError as cpe:
        if not verbose:
            banner("STDOUT", char="-")
            print(cpe.stdout)
            banner("STDERR", char="-")
            print(cpe.stderr)
        banner(["COMMAND FAILED", " ".join(command)], fail=True)
        raise


