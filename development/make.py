"""Helper functions for Maker Scripts."""

import os
import stat
import subprocess
import sys
import tempfile
from pprint import pprint
from typing import Any, Callable

import semver


def banner(
    lines: str | list[str],
    symbol: str = "",
    char: str = "#",
    lf: str = "\n",
    fail: bool = False,
) -> None:
    """Prints a banner to console.

    If given a string, prints the given string.
    If given a list of strings, prints each given string into a separate line.
    If fail is true, mark the banner with red blinking lights.
    """
    # This is a sanity check while developing which can be safely removed in production.
    assert char, "char must not be empty"  # nosec

    if not isinstance(lines, list):
        lines = [lines]
    char = char[0]
    symbol = symbol[0] if symbol else char

    out = [lf]

    if fail:
        # failure banner
        for line in lines:
            out += [f"🚨 {line}", lf]
        out += [lf]

    else:
        # informational banner
        width = len(max(lines, key=len))

        out += [f"{char * (width + 8)}{lf}"]
        left = symbol * 3
        right = symbol * 3 if symbol == char else ""
        for line in lines:
            out += [f"{left} {line.center(width)} {right}", lf]
        out += [out[1]]

    sys.stdout.writelines(out)


def subprocess_run(
    command: list[str],
    environment: dict[str, Any] | None = None,
    verbose: bool = False,
    debug: bool = False,
) -> None:
    """Runs the given command as subprocess.

    If `verbose` is false (the default), captures all output from the command
    and prints the output only if the command fails.
    If `debug` is true (default is false), prints the command and environment.
    """
    if not environment:
        environment = {}
    try:
        if debug:
            banner("COMMAND", char="-")
            pprint(command)
            banner("ENVIRONMENT", char="-")
            pprint(environment)
        if verbose:
            print()
        subprocess.run(  # nosec
            command,
            check=True,
            text=True,
            capture_output=not verbose,
            env={**os.environ.copy(), **environment},
        )
    except subprocess.CalledProcessError as cpe:
        if not verbose:
            banner("STDOUT", char="-")
            print(cpe.stdout)
            banner("STDERR", char="-")
            print(cpe.stderr)
        banner(["COMMAND FAILED", " ".join(command)], fail=True)
        raise


def sizeof_fmt(
    num: float,
    iec: bool = True,
    separator: str = "",
    precision: int = 2,
    sign: bool = False,
) -> str:
    """Formats the given number using either decimal or binary units.

    Arguments:
        num: The number to be formatted.
        iec: If true use binary units, decimal otherwise. Defaults to True.
        separator: Separator between formatted number and unit. Defaults to "".
        precision: Precision to use when rounding the number. Defaults to 2.
        sign: If true, adds a plus sign to positive numbers. Defaults to False.

    Returns:
        A string with the formatted number.
    """
    suffix = "B"
    if iec:
        power = 1024
        units = ["", "Ki", "Mi", "Gi", "Ti", "Pi", "Ei", "Zi", "Yi"]
    else:
        power = 1000
        units = ["", "k", "M", "G", "T", "P", "E", "Z", "Y"]

    plus = "+" if sign and num > 0 else ""
    fmt = "{0:{1}.{2}f}{3}{4}{5}"
    prec = 0
    for unit in units[:-1]:  # noqa
        if abs(round(num, precision)) < power:
            break
        num /= float(power)
        prec = precision
    else:
        unit = units[-1]
    return fmt.format(num, plus, prec, separator, unit, suffix)


def get_version(or_exit_using: Callable) -> semver.VersionInfo:
    """Reads the current version from the version file.

    On error exits with the error message generated by the given callable.
    """
    try:
        with open("VERSION", "r") as f:
            version_str = f.readline()
            version = semver.VersionInfo.parse(version_str)
            return version
    except (FileNotFoundError, ValueError):
        # version file not found or version value invalid
        banner(or_exit_using(), fail=True)
        sys.exit(1)


def write_version(version: semver.VersionInfo) -> None:
    """Writes the given version to the version file.

    Tries to be as robust as possible.
    """
    file_descriptor, file_name = tempfile.mkstemp(suffix=".bak", prefix="tmp", text=True)
    try:
        with os.fdopen(file_descriptor, "w") as f:
            f.write(str(version))
        os.chmod(file_name, stat.S_IREAD | stat.S_IWRITE | stat.S_IRGRP | stat.S_IROTH)
        os.replace(file_name, "VERSION")
        file_name = None
    finally:
        if file_name is not None:
            try:
                os.unlink(file_name)
            # SECURITY: Nothing to do if unlink fails.
            except BaseException:  # nosec
                pass
